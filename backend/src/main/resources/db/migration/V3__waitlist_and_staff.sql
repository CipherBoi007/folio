CREATE TABLE waitlist_entries (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id     bigint      NOT NULL REFERENCES books (id),
    member_id   bigint      NOT NULL REFERENCES members (id),
    status      varchar(20) NOT NULL DEFAULT 'WAITING',
    created_at  timestamptz NOT NULL,
    created_by  bigint      NOT NULL REFERENCES users (id),
    resolved_at timestamptz,
    CONSTRAINT ck_waitlist_status   CHECK (status IN ('WAITING', 'FULFILLED', 'CANCELLED')),
    CONSTRAINT ck_waitlist_resolved CHECK ((status = 'WAITING') = (resolved_at IS NULL))
);

CREATE UNIQUE INDEX uq_waitlist_waiting ON waitlist_entries (book_id, member_id) WHERE status = 'WAITING';
CREATE INDEX ix_waitlist_book_queue ON waitlist_entries (book_id, created_at) WHERE status = 'WAITING';
CREATE INDEX ix_waitlist_member ON waitlist_entries (member_id) WHERE status = 'WAITING';

