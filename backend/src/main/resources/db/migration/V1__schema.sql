CREATE TABLE publishers (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL,
    CONSTRAINT ck_publishers_name CHECK (btrim(name) <> '')
);
CREATE UNIQUE INDEX uq_publishers_name ON publishers (lower(name));

CREATE TABLE authors (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL,
    CONSTRAINT ck_authors_name CHECK (btrim(name) <> '')
);
CREATE UNIQUE INDEX uq_authors_name     ON authors (lower(name));
CREATE INDEX        ix_authors_name_trgm ON authors USING gin (lower(name) gin_trgm_ops);

-- Catalogue ------------------------------------------------------------------------------------------

CREATE TABLE books (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn13             char(13)     NOT NULL,
    title              varchar(300) NOT NULL,
    subtitle           varchar(300),
    genre_id           integer      NOT NULL REFERENCES genres (id),
    publisher_id       bigint       REFERENCES publishers (id),
    language_code      varchar(8)   NOT NULL DEFAULT 'en' REFERENCES languages (code),
    published_year     smallint,
    pages              integer,
    shelf_location     varchar(20),
    description        text,
    cover_url          varchar(500),
    total_quantity     integer      NOT NULL DEFAULT 0,
    available_quantity integer      NOT NULL DEFAULT 0,
    version            bigint       NOT NULL DEFAULT 0,
    created_at         timestamptz  NOT NULL DEFAULT now(),
    updated_at         timestamptz  NOT NULL DEFAULT now(),
    deleted_at         timestamptz,
    -- Not partial: a soft-deleted book keeps its ISBN reserved.
    CONSTRAINT uq_books_isbn13             UNIQUE (isbn13),
    CONSTRAINT ck_books_isbn13_format      CHECK (isbn13 ~ '^97[89][0-9]{10}$'),
    CONSTRAINT ck_books_total_nonneg       CHECK (total_quantity >= 0),
    CONSTRAINT ck_books_available_nonneg   CHECK (available_quantity >= 0),
    CONSTRAINT ck_books_available_le_total CHECK (available_quantity <= total_quantity),
    CONSTRAINT ck_books_published_year     CHECK (published_year IS NULL OR published_year BETWEEN 1000 AND 2100),
    CONSTRAINT ck_books_pages              CHECK (pages IS NULL OR pages > 0),
    CONSTRAINT ck_books_title_not_blank    CHECK (btrim(title) <> '')
);

CREATE INDEX ix_books_title_trgm ON books USING gin (lower(title) gin_trgm_ops);
CREATE INDEX ix_books_title      ON books (lower(title));
CREATE INDEX ix_books_genre      ON books (genre_id);
CREATE INDEX ix_books_publisher  ON books (publisher_id);
CREATE INDEX ix_books_language   ON books (language_code);
CREATE INDEX ix_books_live       ON books (id) WHERE deleted_at IS NULL;

CREATE TABLE book_authors (
    book_id   bigint   NOT NULL REFERENCES books (id) ON DELETE CASCADE,
    author_id bigint   NOT NULL REFERENCES authors (id),
    position  integer  NOT NULL,
    PRIMARY KEY (book_id, author_id),
    CONSTRAINT ck_book_authors_position CHECK (position >= 1)
);

CREATE INDEX ix_book_authors_author ON book_authors (author_id);

