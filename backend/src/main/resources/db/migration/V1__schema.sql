CREATE INDEX ix_members_name_trgm ON members USING gin (lower(full_name) gin_trgm_ops);
CREATE INDEX ix_members_phone     ON members (phone);
CREATE INDEX ix_members_live      ON members (id) WHERE deleted_at IS NULL;

-- Circulation ----------------------------------------------------------------------------------------

-- A loan is active while returned_at is null; status is derived, never stored.
CREATE TABLE loans (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id       bigint      NOT NULL REFERENCES books (id),
    member_id     bigint      NOT NULL REFERENCES members (id),
    issued_at     timestamptz NOT NULL,
    due_date      date        NOT NULL,
    returned_at   timestamptz,
    renewal_count smallint    NOT NULL DEFAULT 0,
    issued_by     bigint      NOT NULL REFERENCES users (id),
    returned_by   bigint      REFERENCES users (id),
    CONSTRAINT ck_loans_renewal_count  CHECK (renewal_count BETWEEN 0 AND 1),
    CONSTRAINT ck_loans_return_fields  CHECK ((returned_at IS NULL) = (returned_by IS NULL)),
    CONSTRAINT ck_loans_returned_after CHECK (returned_at IS NULL OR returned_at >= issued_at)
);

CREATE UNIQUE INDEX uq_loans_active_member_book ON loans (member_id, book_id) WHERE returned_at IS NULL;
CREATE INDEX ix_loans_member_active ON loans (member_id) WHERE returned_at IS NULL;
CREATE INDEX ix_loans_book_active   ON loans (book_id) WHERE returned_at IS NULL;
CREATE INDEX ix_loans_due_active    ON loans (due_date) WHERE returned_at IS NULL;
CREATE INDEX ix_loans_member        ON loans (member_id, issued_at DESC);
CREATE INDEX ix_loans_book          ON loans (book_id, issued_at DESC);
CREATE INDEX ix_loans_issued_at     ON loans (issued_at);
CREATE INDEX ix_loans_returned_at   ON loans (returned_at) WHERE returned_at IS NOT NULL;

CREATE TABLE inventory_transactions (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id          bigint      NOT NULL REFERENCES books (id),
    type             varchar(20) NOT NULL,
    quantity_change  integer     NOT NULL,
    total_before     integer     NOT NULL,
    total_after      integer     NOT NULL,
    available_before integer     NOT NULL,
    available_after  integer     NOT NULL,
    reason           varchar(40),
    note             varchar(500),
    loan_id          bigint      REFERENCES loans (id),
    performed_by     bigint      NOT NULL REFERENCES users (id),
    performed_at     timestamptz NOT NULL,
    CONSTRAINT ck_inv_type CHECK (type IN ('INITIAL_STOCK', 'STOCK_IN', 'STOCK_OUT', 'ISSUE', 'RETURN')),
    CONSTRAINT ck_inv_nonneg CHECK (total_before >= 0 AND total_after >= 0 AND available_before >= 0 AND available_after >= 0),
    CONSTRAINT ck_inv_available_le_total CHECK (available_before <= total_before AND available_after <= total_after),
    CONSTRAINT ck_inv_available_delta CHECK (available_after - available_before = quantity_change),
    CONSTRAINT ck_inv_total_delta CHECK (
        CASE WHEN type IN ('ISSUE', 'RETURN') THEN total_after = total_before
             ELSE total_after - total_before = quantity_change END),
    CONSTRAINT ck_inv_sign CHECK (
        CASE WHEN type IN ('INITIAL_STOCK', 'STOCK_IN', 'RETURN') THEN quantity_change > 0
             ELSE quantity_change < 0 END),
    CONSTRAINT ck_inv_circulation_unit CHECK (type NOT IN ('ISSUE', 'RETURN') OR abs(quantity_change) = 1),
    CONSTRAINT ck_inv_loan_link CHECK ((type IN ('ISSUE', 'RETURN')) = (loan_id IS NOT NULL)),
    CONSTRAINT ck_inv_stock_reason CHECK (type NOT IN ('STOCK_IN', 'STOCK_OUT') OR reason IS NOT NULL)
);

CREATE INDEX ix_inv_book_performed  ON inventory_transactions (book_id, performed_at DESC);
CREATE INDEX ix_inv_performed       ON inventory_transactions (performed_at DESC);
CREATE INDEX ix_inv_type_performed  ON inventory_transactions (type, performed_at DESC);
CREATE INDEX ix_inv_actor_performed ON inventory_transactions (performed_by, performed_at DESC);
CREATE INDEX ix_inv_loan            ON inventory_transactions (loan_id) WHERE loan_id IS NOT NULL;

-- The rate is captured per fine so later rate changes never alter history.
CREATE TABLE fines (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id         bigint        NOT NULL REFERENCES loans (id),
    overdue_days    integer       NOT NULL,
    daily_rate      numeric(10,2) NOT NULL,
    amount          numeric(10,2) GENERATED ALWAYS AS (overdue_days * daily_rate) STORED,
    status          varchar(20)   NOT NULL DEFAULT 'UNPAID',
    resolved_at     timestamptz,
    resolved_by     bigint        REFERENCES users (id),
    resolution_note varchar(500),
    created_at      timestamptz   NOT NULL,
    CONSTRAINT uq_fines_loan         UNIQUE (loan_id),
    CONSTRAINT ck_fines_overdue_days CHECK (overdue_days > 0),
    CONSTRAINT ck_fines_daily_rate   CHECK (daily_rate > 0),
    CONSTRAINT ck_fines_status       CHECK (status IN ('UNPAID', 'PAID', 'WAIVED')),
    CONSTRAINT ck_fines_resolution   CHECK (
        (status = 'UNPAID' AND resolved_at IS NULL AND resolved_by IS NULL) OR
        (status = 'PAID'   AND resolved_at IS NOT NULL AND resolved_by IS NOT NULL) OR
        (status = 'WAIVED' AND resolved_at IS NOT NULL AND resolved_by IS NOT NULL
                           AND resolution_note IS NOT NULL AND btrim(resolution_note) <> ''))
);

CREATE INDEX ix_fines_status ON fines (status, created_at DESC);

