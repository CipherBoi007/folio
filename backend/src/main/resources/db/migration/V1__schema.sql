    CONSTRAINT uq_members_email             UNIQUE (email),
    CONSTRAINT ck_members_email_lower       CHECK (email = lower(email)),
    CONSTRAINT ck_members_membership_number CHECK (membership_number ~ '^FOL-[0-9]{4}-[0-9]{4,}$'),
    CONSTRAINT ck_members_phone             CHECK (phone ~ '^[6-9][0-9]{9}$'),
    CONSTRAINT ck_members_postal_code       CHECK (postal_code IS NULL OR postal_code ~ '^[1-9][0-9]{5}$'),
    CONSTRAINT ck_members_status            CHECK (status IN ('ACTIVE', 'INACTIVE', 'SUSPENDED')),
    CONSTRAINT ck_members_name_not_blank    CHECK (btrim(full_name) <> '')
