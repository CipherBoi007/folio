CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- Staff and sessions ---------------------------------------------------------------------------------

CREATE TABLE users (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  varchar(120) NOT NULL,
    email                 varchar(254) NOT NULL,
    password_hash         varchar(100) NOT NULL,
    role                  varchar(20)  NOT NULL,
    active                boolean      NOT NULL DEFAULT true,
    failed_login_attempts smallint     NOT NULL DEFAULT 0,
    locked_until          timestamptz,
    last_login_at         timestamptz,
    created_at            timestamptz  NOT NULL DEFAULT now(),
    updated_at            timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_email           UNIQUE (email),
    CONSTRAINT ck_users_email_lower     CHECK (email = lower(email)),
    CONSTRAINT ck_users_role            CHECK (role IN ('ADMIN', 'LIBRARIAN')),
    CONSTRAINT ck_users_failed_attempts CHECK (failed_login_attempts >= 0)
);

CREATE TABLE user_sessions (
    id             uuid         PRIMARY KEY,
    user_id        bigint       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at     timestamptz  NOT NULL,
    last_used_at   timestamptz  NOT NULL,
    expires_at     timestamptz  NOT NULL,
    revoked_at     timestamptz,
    revoked_reason varchar(30),
    ip_address     varchar(45),
    user_agent     varchar(300),
    CONSTRAINT ck_sessions_expiry  CHECK (expires_at > created_at),
    CONSTRAINT ck_sessions_revoked CHECK ((revoked_at IS NULL) = (revoked_reason IS NULL)),
    CONSTRAINT ck_sessions_reason  CHECK (revoked_reason IN ('LOGOUT', 'TOKEN_REUSE', 'REVOKED_BY_USER', 'ACCOUNT_DISABLED'))
);

CREATE INDEX ix_sessions_user_active ON user_sessions (user_id) WHERE revoked_at IS NULL;
CREATE INDEX ix_sessions_expires     ON user_sessions (expires_at);

-- Refresh tokens are stored only as SHA-256 hashes. Each rotation links the old token to its successor.
CREATE TABLE refresh_tokens (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id     uuid        NOT NULL REFERENCES user_sessions (id) ON DELETE CASCADE,
    token_hash     char(64)    NOT NULL,
    issued_at      timestamptz NOT NULL,
    expires_at     timestamptz NOT NULL,
    rotated_at     timestamptz,
    replaced_by_id bigint      REFERENCES refresh_tokens (id) ON DELETE SET NULL,
    CONSTRAINT uq_refresh_tokens_hash   UNIQUE (token_hash),
    CONSTRAINT ck_refresh_tokens_expiry CHECK (expires_at > issued_at)
);

CREATE INDEX ix_refresh_tokens_session ON refresh_tokens (session_id);

